#include <iostream>

int main()
{
    float firstNum = 20;
    float secondNum = 10;

    std::cout << "Addition = " << firstNum + secondNum << '\n';
    std::cout << "Subtraction = " << firstNum - secondNum << '\n';
    std::cout << "Multiplication = " << firstNum * secondNum << '\n';
    std::cout << "Division = " << firstNum / secondNum << '\n';

    return 0;
}
